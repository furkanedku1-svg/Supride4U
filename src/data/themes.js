// Tema nesnesini CSS değişkenlerine çevirir.
export function themeVars(t) {
  return {
    '--bg1': t.bg[0],
    '--bg2': t.bg[1],
    '--bg3': t.bg[2],
    '--box': t.box,
    '--box-dark': t.boxDark,
    '--box-light': t.boxLight,
    '--ribbon': t.ribbon,
    '--ribbon-dark': t.ribbonDark,
    '--accent': t.accent,
    '--accent-soft': t.accentSoft,
    '--on-accent': t.onAccent || (t.dark ? '#17193d' : '#ffffff'),
    '--ink': t.ink,
    '--ink-soft': t.inkSoft,
    '--glass': t.glass,
    '--glass-border': t.glassBorder,
    '--shadow-rgb': t.shadow,
  }
}
